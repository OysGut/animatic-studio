create or replace function public.touch_activity() returns void
language plpgsql security definer set search_path = '' as $$
declare v_user uuid := (select auth.uid());
begin
  if v_user is null then return; end if;
  insert into public.account_status (user_id, last_active_at, last_seen_at) values (v_user, now(), now())
    on conflict (user_id) do update set
      last_active_at = case
        when public.account_status.last_active_at is null
          or public.account_status.last_active_at < now() - interval '1 hour' then now()
        else public.account_status.last_active_at end,
      last_seen_at = now()
    where public.account_status.last_seen_at is null
       or public.account_status.last_seen_at < now() - interval '5 minutes'
       or public.account_status.last_active_at is null
       or public.account_status.last_active_at < now() - interval '1 hour';
end $$;
revoke all on function public.touch_activity() from public, anon;
grant execute on function public.touch_activity() to authenticated;

-- ---------- 4. Punkter til forsiden ----------
-- Forskyvning: h = md5('b117:' || user_id); u1, u2 i [0,1) fra de to første 32-biters ordene.
-- Avstand 2 + 10·u1 km, retning 2π·u2. Samme formel som offsetPoint i src/core/globe.
create function public.globe_points()
returns table (lat double precision, lon double precision, active boolean)
language sql stable security definer set search_path = '' as $$
  with users as (
    select p.user_id,
           coalesce(c.lat, k.lat) as base_lat,
           coalesce(c.lon, k.lon) as base_lon,
           coalesce(s.last_seen_at > now() - interval '1 hour', false)
             or coalesce(s.last_active_at > now() - interval '1 hour', false) as active,
           md5('b117:' || p.user_id::text) as h
    from public.profiles p
    left join public.account_status s on s.user_id = p.user_id
    left join private.globe_places c on c.id = p.city and c.country = p.country
    left join private.globe_places k on k.country = p.country and k.capital
    where p.country is not null
      and coalesce(s.status, 'active') = 'active'
      and coalesce(c.lat, k.lat) is not null
  ), off as (
    select base_lat, base_lon, active,
           (2 + 10 * (('x' || substr(h, 1, 8))::bit(32)::bigint / 4294967296.0)) / 6371.0 as d,
           2 * pi() * (('x' || substr(h, 9, 8))::bit(32)::bigint / 4294967296.0) as b
    from users
  )
  select greatest(-89.9, least(89.9, base_lat + degrees(d * cos(b)))),
         case when base_lon + degrees(d * sin(b) / cos(radians(base_lat))) > 180
                then base_lon + degrees(d * sin(b) / cos(radians(base_lat))) - 360
              when base_lon + degrees(d * sin(b) / cos(radians(base_lat))) < -180
                then base_lon + degrees(d * sin(b) / cos(radians(base_lat))) + 360
              else base_lon + degrees(d * sin(b) / cos(radians(base_lat))) end,
         active
  from off
  order by 1, 2
$$;
revoke all on function public.globe_points() from public;
grant execute on function public.globe_points() to anon, authenticated, service_role;

