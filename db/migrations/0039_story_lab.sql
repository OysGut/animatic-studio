-- =====================================================================================
-- Animatic Studio – migrasjon 0039: Story Lab, datamodell (SL1).
-- 1. story_profiles: karakterprofilen (psykologi, tale, dramatikk, person) for en ressurs av typen
--    «character» eller «animal». Høyst én aktiv profil per ressurs.
-- 2. story_profile_stages: profilendringer over karakterbuen fra en scene (fortellingstid). Høyst ett aktivt
--    stadium per karakter og scene.
-- 3. story_facts: fakta og hemmeligheter, når de skjer (scene) og hvem som vet dem fra hvilken scene.
--    De tre tabellene er prosjektdata og skrives bare via apply_changes (kommandoer med angring).
-- 4. story_sessions og story_suggestions: arbeidslogg for samtaler, intervju og analyser, og forslag fra dem.
--    Skrives bare av serverfunksjonene (service role), ikke via apply_changes.
-- 5. apply_changes: som 0028, med de tre nye tabellene i v_tables (ellers uendret).
-- 6. delete_project (som 0021), purge_project_assets (som 0035) og purge_removed_assets (som 0029): sletter
--    eller verner Story Lab-radene.
-- Lesing for prosjektmedlemmer; klienten kan ikke skrive direkte (som 0019).
-- Ingen SQL mot lagringen (storage). Ingen eksisterende data endres.
-- Kjøres ÉN gang i Lovable Cloud etter 0038. Endres aldri etter kjøring.
-- =====================================================================================

create table public.story_profiles (
  id uuid primary key,
  project_id uuid not null references public.projects (id),
  asset_id uuid not null references public.assets (id) on delete restrict,
  profile jsonb not null check (jsonb_typeof(profile) = 'object' and pg_column_size(profile) <= 65536),
  removed boolean not null default false,
  revision integer not null default 1,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users (id)
);
create index story_profiles_project_idx on public.story_profiles (project_id);
create unique index story_profiles_one_live on public.story_profiles (project_id, asset_id) where not removed;
alter table public.story_profiles enable row level security;
create policy story_profiles_read on public.story_profiles for select to authenticated
  using (private.is_project_member(project_id));
revoke insert, update, delete, truncate on public.story_profiles from anon, authenticated;
grant select on public.story_profiles to authenticated;
