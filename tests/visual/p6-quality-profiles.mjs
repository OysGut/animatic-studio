/** M8 profile choices, immutable provenance and queue continuation. No paid calls. */
import { harness } from "./mts-harness.mjs";
const h = harness("/tmp/browser/p6-quality-profiles");
const clip=h.rows.audio_clips.find(c=>c.kind==="dialogue" && c.block_id && !c.removed);
if (!clip) throw new Error("Missing dialogue fixture");
const pid="00000000-0000-7000-8000-000000006301";
h.rows.quality_profiles=[{id:pid,project_id:h.fx.project.id,name:"Final test",revision:1,removed:false,spec:{effort:"premium",variants:2,resolution:"1K",models:{speech:"eleven_multilingual_v2"},export:{format:"png-seq",alpha:"premultiplied",bitrateKbps:16000}}}];
h.fx.project.active_quality_profile_id=pid;
for (const lang of ["nb","en"]) await h.scenario(`p6-${lang}`,clip.occurrence_id,lang,async page=>{
  await page.getByTestId("scene-script").locator(`[data-script-block="${clip.block_id}"] [data-script-text]`).dblclick();
  await page.getByTestId("dialogue-character-select").selectOption(h.rows.assets.find(a=>a.kind==="character").id);
  await page.getByTestId("dialogue-generate-open").click();
  const picker=page.getByTestId("quality-profile-picker");
  h.check(await picker.inputValue()==="active","active project profile initially selected");
  await page.getByTestId("voice-select").selectOption("mock_voice");
  await picker.selectOption(pid); h.check(await picker.inputValue()===pid,"explicit profile override");
  h.check(await page.getByTestId("voice-model").inputValue()==="eleven_multilingual_v2","profile changes speech estimate model");
  await page.getByTestId("dialogue-generation-start").click();
  h.check(!h.state.rpcs.some(r=>r.name==="generateSpeech"),"no call before approval");
  await page.getByTestId("record-audio-dialog").screenshot({path:`${h.out}/speech-${lang}.png`});
  await page.getByTestId("dialogue-generation-approve").click();
  await h.eventually(()=>h.state.rpcs.some(r=>r.name==="generateSpeech"),5000);
  const call=h.state.rpcs.find(r=>r.name==="generateSpeech");
  h.check(call?.body.qualityProfile?.id===pid && call.body.qualityProfile.name==="Final test","approved immutable profile snapshot sent");
  await page.getByTestId("record-audio-dialog").getByRole("button",{name:lang==="nb"?"Avbryt":"Cancel",exact:true}).last().click();
  await page.getByTestId("alpha-export-open").click();
  h.check(await page.getByTestId("alpha-mode").inputValue()==="premultiplied","alpha profile applied");
  await page.getByTestId("alpha-export-dialog").screenshot({path:`${h.out}/alpha-${lang}.png`});
  await page.getByTestId("quality-profile-picker").selectOption("none");
  h.check(await page.getByTestId("quality-profile-picker").inputValue()==="none","no-profile override");
  await page.getByTestId("alpha-cancel").click();
  await page.goto(h.base+h.P+`/bibliotek?asset=${h.rows.assets.find(a=>a.kind==="character").id}`);
  await page.getByTestId("dialogue-batch-open").click();
  await page.getByTestId("quality-profile-picker").selectOption(pid);
  h.check(await page.getByTestId("quality-profile-picker").inputValue()===pid,"DV batch profile choice");
  await page.getByTestId("dialogue-batch-dialog").screenshot({path:`${h.out}/batch-${lang}.png`});
});
await h.finish();
