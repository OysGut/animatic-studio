/** DV3: existing editor, preserved alternatives and explicitly confirmed links. No real services. */
import { harness } from "./mts-harness.mjs";
const h = harness("/tmp/browser/dv3");
const clip = h.rows.audio_clips.find(c => c.kind === "dialogue" && c.block_id && !c.removed);
if (!clip) throw new Error("Missing dialogue fixture");
for (const lang of ["nb", "en"]) await h.scenario(`dv3-${lang}`, clip.occurrence_id, lang, async page => {
  await page.getByTestId("scene-script").locator(`[data-script-block="${clip.block_id}"] [data-script-text]`).dblclick();
  const dialog = page.getByTestId("record-audio-dialog"); await dialog.waitFor();
  h.check(await page.getByTestId("record-line-select").inputValue() === clip.block_id, "correct line preselected");
  h.check(await page.getByTestId("dialogue-active-text").isVisible(), "active text remains readable");
  h.check(await page.getByTestId("dialogue-character-name").isVisible(), "speaker name visible");
  h.check(await page.getByTestId("dialogue-headphones").isVisible(), "headphone warning visible");
  const versions = page.getByTestId("dialogue-version");
  h.check(await versions.count() >= 2, "preserved versions stacked");
  h.check(await page.getByTestId("dialogue-version-wave").count() === await versions.count(), "one waveform for every version");
  h.check(await versions.locator('[data-testid="dialogue-version-activate"]:disabled').count() === 1, "exactly one active film version");
  h.check(await versions.locator('[data-testid="dialogue-version-delete"]:disabled').count() === 1, "active version cannot be deleted");
  await dialog.getByRole("button", { name: lang === "nb" ? "Ta opp" : "Record", exact: true }).click();
  const stopRecord = dialog.getByRole("button", { name: lang === "nb" ? "Stopp" : "Stop", exact: true }); await stopRecord.waitFor();
  h.check(await page.getByTestId("dialogue-active-text").isVisible(), "active line remains visible during scene recording");
  await page.waitForTimeout(350); await stopRecord.click();
  await dialog.locator("audio[controls]").waitFor();
  h.check(await dialog.locator("audio[controls]").isVisible(), "recording is preserved for review before save");
  await dialog.getByRole("button", { name: lang === "nb" ? "Forkast" : "Discard", exact: true }).click();
  const before = h.state.commands.length;
  const inactive = versions.filter({ has: page.locator('[data-testid="dialogue-version-delete"]:not(:disabled)') }).first();
  await inactive.getByTestId("dialogue-version-delete").click();
  h.check(h.state.commands.length === before, "opening deletion confirmation writes nothing");
  h.check(await page.getByTestId("dialogue-version-delete-confirm").isVisible(), "explicit deletion confirmation");
  await page.getByRole("button", { name: lang === "nb" ? "Avbryt" : "Cancel", exact: true }).first().click();
  h.check(await versions.count() >= 2, "cancel preserves alternatives");
  await page.getByTestId("dialogue-link-open").click();
  h.check(await page.getByTestId("dialogue-link-list").isVisible(), "legacy links are suggestions in a list");
  h.check(h.state.commands.length === before, "suggestions do not auto-link");
  await dialog.screenshot({ path: `${h.out}/editor-${lang}.png` });
  await page.getByTestId("dialogue-link-list").locator('input[type="checkbox"]').first().check();
  await page.getByTestId("dialogue-link-confirm").click();
  h.check(h.state.commands.some(c => c.type === "SetDialogueCharacter"), "confirmed legacy link writes character command");
  const activeId = await versions.filter({ has: page.locator('[data-testid="dialogue-version-activate"]:disabled') }).first().getAttribute("data-version-id");
  const previewButton = inactive.getByTestId("dialogue-version-preview"); await previewButton.click();
  h.check((await previewButton.innerText()).includes(lang === "nb" ? "Stopp" : "Stop"), "alternative preview starts");
  h.check(!h.state.commands.some(c => c.type === "SetActiveDialogueVersion"), "preview never changes film active version");
  await previewButton.click();
  await inactive.getByTestId("dialogue-version-activate").click();
  h.check(h.state.commands.some(c => c.type === "SetActiveDialogueVersion"), "explicit film choice changes active version");
  h.check(await versions.count() >= 2, "switch preserves alternatives");
  const old = page.locator(`[data-version-id="${activeId}"]`);
  await old.getByTestId("dialogue-version-delete").click(); await page.getByTestId("dialogue-version-delete-confirm").click();
  h.check(h.state.commands.some(c => c.type === "SetDialogueVersionRemoved" && c.removed === true), "only confirmed deletion removes inactive version");
  await dialog.getByRole("button", { name: lang === "nb" ? "Avbryt" : "Cancel", exact: true }).last().click();
  h.check(await page.getByTestId("scene-character-track").count() > 0, "scene timeline projects character rows");
  await page.getByTestId("scene-tab-animation").click();
  h.check(await page.getByTestId("anim-dialogue-segment").count() > 0, "animation timeline contains dialogue rows");
});
await h.finish();