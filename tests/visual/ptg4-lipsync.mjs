/** PTG4: fixed local words, command mocks and real ZIP/PDF; no AI or paid calls. */
import { harness } from './mts-harness.mjs';
import { unzipSync } from 'fflate';
import { readFileSync } from 'node:fs';
const h=harness('/tmp/browser/ptg4-lipsync'),lang=process.env.UI_LANG??'nb';
const clip=h.rows.audio_clips.find(c=>c.kind==='dialogue'&&c.block_id),character=h.rows.assets.find(a=>a.kind==='character');
if(!clip||!character)throw new Error('fixture');
clip.character_asset_id=character.id;
const block=h.rows.script_blocks.find(b=>b.id===clip.block_id);block.text='pappa';
for(const revision of h.rows.script_block_revisions.filter(r=>r.block_id===block.id&&r.rev===block.current_rev))revision.text=block.text;
const variant=h.rows.asset_variants.find(v=>v.asset_id===clip.asset_id);
const version=h.rows.asset_versions.find(v=>v.variant_id===variant?.id);
if(!version)throw new Error('audio version');
version.alignment={format:1,blockId:block.id,text:'pappa',words:[{text:'pappa',startMs:0,endMs:1000,loss:null}],provider:null,model:null,loss:null,at:'2026-10-22T00:00:00Z'};
h.fx.project.code='PTG4-TEST';h.rows.mouth_sets=[];h.rows.mouth_tracks=[];
h.hooks.rest=(table,req)=>{
 if(table==='rpc/reserve_interchange_export'){const body=JSON.parse(req.postData());return{batchId:'00000000-0000-7000-8000-000000008204',versions:Object.fromEntries(body.p_occurrence_ids.map(id=>[id,1]))};}
 if(table==='rpc/complete_interchange_export')return '00000000-0000-7000-8000-000000008205';
};
await h.scenario(`ptg4-${lang}`,clip.occurrence_id,lang,async page=>{
 await page.getByTestId('ptg4-mouth-track').waitFor();
 h.check(await page.getByTestId('ptg4-mouth-track').isVisible(),`${lang}: munnrad i sammenslått Scene-tidslinje`);
 await page.getByTestId('ptg4-set').first().click();
 await page.getByTestId('ptg4-variant-A').click();
 h.check(await page.getByTestId('ptg4-variant-A-search').isVisible(),`${lang}: søkbar tastaturstyrt variantvelger`);
 await page.getByTestId('ptg4-variant-A-search').press('Escape');
 await page.getByTestId('ptg4-save-set').click();
 h.check(await h.eventually(()=>h.state.commands.some(c=>c.type==='SaveMouthSet')),`${lang}: munnsett gjennom kommando`);
 await page.getByTestId('ptg4-draft').first().click();
 await page.getByTestId('ptg4-apply').waitFor();
 h.check(!h.state.commands.some(c=>c.type==='SaveMouthTrack'),`${lang}: utkast er ikke lagret automatisk`);
 await page.getByTestId('ptg4-apply').click();
 h.check(await h.eventually(()=>h.state.commands.some(c=>c.type==='SaveMouthTrack')),`${lang}: bruker godkjenner munnspor`);
 await page.getByTestId('ptg4-span').first().click();
 const before=h.state.commands.filter(c=>c.type==='SaveMouthTrack').at(-1).track.spans.length;
 await page.getByTestId('ptg4-split').click();
 h.check(await h.eventually(()=>h.state.commands.filter(c=>c.type==='SaveMouthTrack').at(-1).track.spans.length===before+1),`${lang}: del lagres`);
 await page.getByTestId('ptg4-merge').click();
 h.check(await h.eventually(()=>h.state.commands.filter(c=>c.type==='SaveMouthTrack').at(-1).track.spans.length===before),`${lang}: slå sammen lagres`);
 await page.getByTestId('ptg4-start').fill('1');
 h.check(await h.eventually(()=>h.state.commands.filter(c=>c.type==='SaveMouthTrack').at(-1).track.spans[0].startFrame===1),`${lang}: grense flyttes`);
 await page.keyboard.press('Escape');
 await page.getByTestId('ptg4-mouth-track').screenshot({path:`${h.out}/${lang}-track.png`});
 const storedSet=h.state.commands.filter(c=>c.type==='SaveMouthSet').at(-1).set;
 const storedTrack=h.state.commands.filter(c=>c.type==='SaveMouthTrack').at(-1).track;
 h.rows.mouth_sets=[{id:storedSet.id,project_id:h.fx.project.id,character_id:storedSet.characterId,system:storedSet.system,variants:storedSet.variants,revision:1,removed:false}];
 h.rows.mouth_tracks=[{id:storedTrack.id,project_id:h.fx.project.id,occurrence_id:storedTrack.occurrenceId,character_id:storedTrack.characterId,set_id:storedTrack.setId,clip_id:storedTrack.clipId,block_id:storedTrack.blockId,language:storedTrack.language,spans:storedTrack.spans,source:storedTrack.source,revision:1,removed:false}];
 await page.goto(h.base+h.P+'/montering',{waitUntil:'networkidle'});
 await page.evaluate(()=>{delete window.showSaveFilePicker;});
 await page.getByRole('button',{name:lang==='en'?'Export animatic':'Eksporter animatic',exact:true}).click();
 const download=page.waitForEvent('download',{timeout:90000});await page.getByTestId('ptg4-export').click();
 const path=`${h.out}/${lang}-mouth.zip`;await(await download).saveAs(path);
 const zip=unzipSync(readFileSync(path));
 h.check(!!zip['mouth-list.pdf']&&!!zip['mouth-list.csv'],`${lang}: PDF og CSV i selvstendig pakke`);
 const json=Object.entries(zip).find(([p])=>p.endsWith('_mouth.json'));
 h.check(!!json,`${lang}: JSON bruker PTG skuddnavn`);
 const dat=Object.entries(zip).find(([p])=>p.endsWith('.dat'));
 h.check(!!dat&&new TextDecoder().decode(dat[1]).startsWith('MohoSwitch1\n'),`${lang}: Moho Papagayo DAT`);
 const pdf=new TextDecoder().decode(zip['mouth-list.pdf']);
 h.check(pdf.includes('/FontFile2'),`${lang}: Noto-font innebygd`);
 const readme=new TextDecoder().decode(zip['LESMEG.txt']);
 h.check(readme.includes('NB Uttale')&&readme.includes('CC0')&&readme.includes('CMUdict')&&readme.includes('BSD'),`${lang}: kilder og lisenser i LESMEG`);
 h.check(!h.state.rpcs.some(r=>/generate|Ai/.test(r.name)),`${lang}: ingen AI eller betalte kall`);
 await page.getByTestId('ptg-export-section').screenshot({path:`${h.out}/${lang}-export.png`});
});
await h.finish();
